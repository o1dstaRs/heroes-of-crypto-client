const presentationDescriptors = Object.fromEntries(
    PRESENTATION_FIELDS.map((field) => [
        field,
        { value: undefined, writable: true, configurable: true, enumerable: false },
    ]),
);

/** Call on the base Unit before its renderer adds any fields. Never hide an existing engine field. */
export function initializeUnitPresentationFields(unit: Unit): void {
    for (const field of PRESENTATION_FIELDS) {
        if (Object.hasOwn(unit, field)) {
            throw new Error(`Unit presentation field conflicts with existing battle state: ${field}`);
        }
    }
    Object.defineProperties(unit, presentationDescriptors);
}
