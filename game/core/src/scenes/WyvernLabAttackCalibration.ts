export function calibrateWyvernAttackChannel(value: number, pose: string, channel: number): number {
    const curve = wyvernAttackCurves[pose];
    if (!curve) return value;
    for (let i = 1; i < curve.source.length; i++) {
        if (value <= curve.source[i][channel]) {
            const low = curve.source[i - 1][channel],
                high = curve.source[i][channel];
            const t = Math.max(0, Math.min(1, (value - low) / Math.max(high - low, 0.00001)));
            return curve.target[i - 1][channel] + t * (curve.target[i][channel] - curve.target[i - 1][channel]);
        }
    }
    return curve.target[curve.target.length - 1][channel];
}
