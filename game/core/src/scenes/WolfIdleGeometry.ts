const smooth = (t: number): number => {
    const x = Math.max(0, Math.min(1, t));
    return x * x * (3 - 2 * x);
};

/** Output coordinates -> source coordinates in the vertically registered pose. */
export function wolfGeometryRegisteredSourcePoint(x: number, y: number, pose: number): { x: number; y: number } {
    if (pose < 0 || pose >= WOLF_POSE_LEG_SPANS.length || y <= 470) return { x, y };
    let lower = 0;
    while (lower < WOLF_GEOMETRY_ROWS.length - 1 && y > WOLF_GEOMETRY_ROWS[lower + 1]) lower++;
    const upper = Math.min(lower + 1, WOLF_GEOMETRY_ROWS.length - 1);
    const mix =
        upper === lower
            ? 0
            : smooth((y - WOLF_GEOMETRY_ROWS[lower]) / (WOLF_GEOMETRY_ROWS[upper] - WOLF_GEOMETRY_ROWS[lower]));
    const targets = WOLF_REFERENCE_LEG_SPANS[lower].map((v, i) => v + (WOLF_REFERENCE_LEG_SPANS[upper][i] - v) * mix);
    const sources = WOLF_POSE_LEG_SPANS[pose][lower].map((v, i) => v + (WOLF_POSE_LEG_SPANS[pose][upper][i] - v) * mix);
    const guardLeft = Math.min(targets[0], sources[0]) - 35;
    const guardRight = Math.max(targets[7], sources[7]) + 35;
    if (x <= guardLeft || x >= guardRight) return { x, y };
    const xs = [guardLeft, ...targets, guardRight];
    const dx = [0, ...sources.map((v, i) => v - targets[i]), 0];
    const dy = [
        0,
        ...targets.map((_, i) => {
            const leg = Math.floor(i / 2);
            return (
                (WOLF_POSE_FOOT_BOTTOM[pose][leg] - WOLF_REFERENCE_FOOT_BOTTOM[leg]) *
                Math.max(0, Math.min(1, (y - 570) / (WOLF_REFERENCE_FOOT_BOTTOM[leg] - 570)))
            );
        }),
        0,
    ];
    let segment = 0;
    while (segment < xs.length - 2 && x > xs[segment + 1]) segment++;
    const t = (x - xs[segment]) / (xs[segment + 1] - xs[segment]);
    return {
        x: x + (dx[segment] + (dx[segment + 1] - dx[segment]) * t) * smooth((y - 470) / 100),
        y: y + dy[segment] + (dy[segment + 1] - dy[segment]) * t,
    };
}

/** Output coordinates -> authored atlas pixels, including the existing rib registration. */
export function wolfGeometrySourcePoint(x: number, y: number, pose: number): { x: number; y: number } {
    if (pose < 0 || pose >= WOLF_POSE_BODY.length) return { x, y };
    const point = wolfGeometryRegisteredSourcePoint(x, y, pose);
    const [top, belly] = WOLF_POSE_BODY[pose];
    const [baseTop, baseBelly] = WOLF_REFERENCE_BODY;
    const sourceY =
        point.y <= baseTop
            ? point.y + top - baseTop
            : point.y <= baseBelly
              ? top + ((point.y - baseTop) * (belly - top)) / (baseBelly - baseTop)
              : belly + ((point.y - baseBelly) * (697 - belly)) / (697 - baseBelly);
    return { x: point.x, y: sourceY };
}
