const RADII = [
    [22, 18],
    [18, 15],
    [22, 24],
    [24, 29],
    [22, 22],
] as const;
type RGB = readonly [number, number, number];
const smooth = (a: number, b: number, value: number): number => {
    const t = Math.max(0, Math.min(1, (value - a) / (b - a)));
    return t * t * (3 - 2 * t);
};

/** Continuous moving material correction. RGB uses 0..1; alpha is the fur-only blend weight. */
export function wolfHeadPaletteColor(
    raw: RGB,
    x: number,
    y: number,
    pose: number,
): {
    color: [number, number, number];
    weight: number;
} {
    const p = WOLF_HEAD_PALETTE[pose];
    const vx = p.nose[0] - p.eye[0],
        vy = p.nose[1] - p.eye[1];
    const length = Math.hypot(vx, vy),
        ex = vx / length,
        ey = vy / length;
    const weights = p.centers.map(([cx, cy], i) => {
        const dx = x - cx,
            dy = y - cy;
        const u = i < 3 ? dx * ex + dy * ey : dx,
            v = i < 3 ? -dx * ey + dy * ex : dy;
        return Math.exp(-0.5 * ((u / RADII[i][0]) ** 2 + (v / RADII[i][1]) ** 2));
    });
    const total = Math.max(
        weights.reduce((sum, w) => sum + w, 0),
        1e-20,
    );
    const color = raw.map(
        (value, c) => (value * weights.reduce((sum, w, i) => sum + w * p.gains[i][c], 0)) / total,
    ) as [number, number, number];
    const [ax, ay, bx, by] = p.collar;
    const edge = ax + ((y - ay) * (bx - ax)) / (by - ay);
    const fur = smooth(-10, 18, x - edge) * (1 - smooth(by + 2, by + 32, y));
    const luma = raw[0] * 0.2126 + raw[1] * 0.7152 + raw[2] * 0.0722;
    const dark = smooth(0.055, 0.13, luma);
    const red = 1 - smooth(1.65, 1.9, raw[0] / Math.max(raw[1], 0.001));
    const eye = smooth(5, 13, Math.hypot(x - p.eye[0], y - p.eye[1]));
    const protectedColor = raw.map((value, c) => value + (color[c] - value) * dark * red * eye) as [
        number,
        number,
        number,
    ];
    return { color: protectedColor, weight: fur };
}

// The shader and CPU helper use the same generated constants and masks.
const glNumber = (value: number): string => (Number.isInteger(value) ? `${value}.0` : String(value));
const glVec = (values: readonly number[]): string => `vec${values.length}(${values.map(glNumber).join(",")})`;
const cases = WOLF_HEAD_PALETTE.map(
    (p, i) => `${i === 0 ? "if" : "else if"}(poseIndex<${i + 0.5}) {
eye=${glVec(p.eye)};nose=${glVec(p.nose)};collar=${glVec(p.collar)};
${p.centers.map((v, k) => `center[${k}]=${glVec(v)};gain[${k}]=${glVec(p.gains[k])};`).join("\n")}
}`,
).join("\n");
export const WOLF_HEAD_PALETTE_GLSL = /* glsl */ `
vec4 headPalette(vec3 raw,vec2 point,float poseIndex) {
    vec2 eye=vec2(0.0),nose=vec2(1.0,0.0),center[5];
    vec3 gain[5];vec4 collar=vec4(0.0,0.0,0.0,1.0);
    ${cases}
    vec2 axis=normalize(nose-eye),normal=vec2(-axis.y,axis.x);
    vec2 radii[5];
    ${RADII.map((v, i) => `radii[${i}]=${glVec(v)};`).join("\n")}
    vec3 sum=vec3(0.0);float total=0.0;
    for(int i=0;i<5;i++) {
        vec2 delta=point-center[i];
        vec2 local=i<3?vec2(dot(delta,axis),dot(delta,normal)):delta;
        local/=radii[i];
        float weight=exp(-0.5*dot(local,local));
        sum+=gain[i]*weight;total+=weight;
    }
    float edge=collar.x+(point.y-collar.y)*(collar.z-collar.x)/(collar.w-collar.y);
    float fur=smoothstep(-10.0,18.0,point.x-edge)*(1.0-smoothstep(collar.w+2.0,collar.w+32.0,point.y));
    float dark=smoothstep(0.055,0.13,dot(raw,vec3(0.2126,0.7152,0.0722)));
    float red=1.0-smoothstep(1.65,1.9,raw.r/max(raw.g,0.001));
    float eyeMask=smoothstep(5.0,13.0,length(point-eye));
    vec3 corrected=mix(raw,raw*sum/max(total,1e-20),dark*red*eyeMask);
    return vec4(corrected,fur);
}
`;
