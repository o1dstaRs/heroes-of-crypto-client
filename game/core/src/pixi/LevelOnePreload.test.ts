test("every approved runtime atlas is available before its first animation", () => {
    const bundles = getSplitBundles({ animationsEnabled: false });
    const loaded = { ...bundles.core, ...bundles.idleAtlases, ...bundles.animations };
    for (const key of required) {
        expect(bundles.excludedFullResolutionUnitAtlases[key], key).toBeUndefined();
        expect(loaded[key]?.src, key).toBeString();
    }
    expect(bundles.deferredUnitAtlases.arbalester_idle_page_00_atlas).toBeDefined();
    expect(bundles.excludedFullResolutionUnitAtlases.wolf_idle_atlas).toBeDefined();
});
