/* Export the game's complete portrait recipe and canonical art, including palette and orientation.
 * Run `bun run --cwd site sync:portraits`; --check verifies without changing any files. */
import { createHash } from "node:crypto";
import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { images } from "../../game/core/src/generated/image_imports";
import { CREATURE_PORTRAIT_ASPECT, resolveCreaturePortraitVisual } from "../../game/core/src/ui/creaturePortraitVisual";
import {
    CHAOS_PORTRAIT_BACKGROUND_FILTER,
    HYDRA_PORTRAIT_NON_EMISSIVE_MASK,
    HYDRA_PORTRAIT_SCALE_MATRIX,
    HYDRA_PORTRAIT_WARM_MASK,
} from "../../game/core/src/ui/creaturePortraitPalette";
import { UNIT_ID_TO_NAME } from "../../game/core/src/ui/unit_ui_constants";
import type { PortraitRecipe } from "../src/lib/portrait";

const SITE = fileURLToPath(new URL("..", import.meta.url));
const ART_DIR = "public/assets/images/units/portraits";
const BACKGROUND_DIR = "public/assets/images/units/portrait-backgrounds";
const RECIPE_FILE = "src/lib/generated/portrait-recipes.json";

export function syncPortraitArt(artSource: string, siteDirectory = SITE, checkOnly = false): void {
    // Framing is authored against the full manifest. A pruned one silently selects a different image
    // under the same crop, producing a giant head or an empty corner instead of the approved portrait.
    if (!Object.keys(images).some((key) => key.endsWith("_portrait_full"))) {
        throw new Error(
            "Portrait export requires the full image manifest. Run `bun run --cwd game/core generate:images`.",
        );
    }

    const outputs = new Map<string, Buffer>();
    const published = new Map<string, string>();
    const publish = (directory: string, sourceUrl: string): string => {
        const filename = basename(new URL(sourceUrl).pathname);
        const key = `${directory}/${filename}`;
        const previous = published.get(key);
        if (previous) return previous;
        const source = join(artSource, filename);
        if (!existsSync(source)) throw new Error(`Missing canonical portrait art: ${filename}`);
        const bytes = readFileSync(source);
        const digest = createHash("sha256").update(bytes).digest("hex").slice(0, 8);
        const served = filename.replace(/\.webp$/, `.${digest}.webp`);
        outputs.set(`${directory}/${served}`, bytes);
        published.set(key, served);
        return served;
    };

    const creatures: Record<string, PortraitRecipe> = {};
    for (const [id, name] of Object.entries(UNIT_ID_TO_NAME)) {
        const visual = resolveCreaturePortraitVisual(Number(id));
        if (!visual) throw new Error(`No game portrait resolved for ${name} (id ${id}).`);
        const slug = name
            .toLowerCase()
            .replace(/[^a-z0-9]+/g, "_")
            .replace(/^_|_$/g, "");
        creatures[slug] = {
            art: publish(ART_DIR, visual.source),
            background: visual.background ? publish(BACKGROUND_DIR, visual.background) : null,
            backgroundOpacity: visual.backgroundOpacity,
            shadeAlpha: Number(visual.backgroundShadeAlpha.toFixed(4)),
            shadeColor: visual.backgroundShadeColor,
            backgroundTone: visual.backgroundTone,
            artPalette: visual.artPalette,
            mirrored: visual.mirrored,
            blurBackdrop: visual.framing.background === "soft",
            fit: visual.framing.fit,
            scale: visual.framing.scale,
            offsetX: visual.framing.offsetX,
            offsetY: visual.framing.offsetY,
        };
    }
    const recipe = {
        $comment:
            "AUTO-GENERATED BY site/scripts/sync_portrait_art.ts — do not edit. Resolved from the game's complete portrait visual and canonical art.",
        aspectRatio: Number(CREATURE_PORTRAIT_ASPECT.toFixed(6)),
        filters: {
            chaosBackground: CHAOS_PORTRAIT_BACKGROUND_FILTER,
            hydraScale: HYDRA_PORTRAIT_SCALE_MATRIX,
            hydraWarmMask: HYDRA_PORTRAIT_WARM_MASK,
            hydraNonEmissiveMask: HYDRA_PORTRAIT_NON_EMISSIVE_MASK,
        },
        creatures: Object.fromEntries(Object.entries(creatures).sort(([a], [b]) => a.localeCompare(b))),
    };
    outputs.set(RECIPE_FILE, Buffer.from(`${JSON.stringify(recipe, null, 4)}\n`));

    // Resolve and read EVERY source before modifying exports. A missing Drive file must not erase the
    // current website portraits or leave a half-written recipe. Never write back to the art masters.
    const stale = [...outputs].filter(([path, bytes]) => {
        const destination = join(siteDirectory, path);
        if (!existsSync(destination)) return true;
        const existing = readFileSync(destination);
        if (path === RECIPE_FILE) {
            // Formatting may compact matrix arrays. Check the complete data, not insignificant JSON
            // whitespace, so targeted `bun fmt` does not make a fresh export appear stale.
            try {
                return JSON.stringify(JSON.parse(existing.toString())) !== JSON.stringify(recipe);
            } catch {
                return true;
            }
        }
        return !existing.equals(bytes);
    });
    const obsolete = [ART_DIR, BACKGROUND_DIR].flatMap((directory) => {
        const absolute = join(siteDirectory, directory);
        return existsSync(absolute)
            ? readdirSync(absolute)
                  .map((file) => `${directory}/${file}`)
                  .filter((path) => !outputs.has(path))
            : [];
    });
    if (checkOnly) {
        if (stale.length || obsolete.length) {
            throw new Error(
                `Website portrait exports are stale. Run sync:portraits.\n${[...stale.map(([path]) => path), ...obsolete].join("\n")}`,
            );
        }
        console.log(`Portrait exports verified: ${Object.keys(creatures).length} complete game recipes.`);
        return;
    }
    for (const [path, bytes] of stale) {
        const destination = join(siteDirectory, path);
        mkdirSync(dirname(destination), { recursive: true });
        writeFileSync(destination, bytes, { mode: 0o644 });
    }
    for (const path of outputs.keys()) chmodSync(join(siteDirectory, path), 0o644);
    for (const path of obsolete) unlinkSync(join(siteDirectory, path));
    console.log(
        `Portraits synced: ${Object.keys(creatures).length} creatures; ${stale.length} updated exports, ${obsolete.length} obsolete files removed.`,
    );
}

if (import.meta.main) {
    const checkOnly = process.argv.includes("--check");
    const source = process.env.HOC_IMAGES_LOC;
    if (source) syncPortraitArt(source, SITE, checkOnly);
    else if (checkOnly) console.log("Skipping canonical portrait byte comparison: HOC_IMAGES_LOC is not set.");
    else throw new Error("HOC_IMAGES_LOC must name the canonical game art directory.");
}
